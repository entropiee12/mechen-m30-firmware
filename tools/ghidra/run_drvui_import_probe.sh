#!/usr/bin/env bash
# Report MIPS16 indirect-call/import-selector pairs in the real M30 B3 bank.
# This is a read-only binutils cross-check for the Ghidra-mapped bank; it never
# executes or modifies firmware.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
DRIVER=${1:-$ROOT/analysis/community/fw/drv_ui.drv}
GHIDRA=${GHIDRA:-/opt/homebrew/Cellar/ghidra/12.2/libexec/support/analyzeHeadless}
JAVA_HOME_OVERRIDE=${JAVA_HOME_OVERRIDE:-/Library/Java/JavaVirtualMachines/temurin-21.jdk/Contents/Home}

[ -f "$DRIVER" ] || { echo "missing driver: $DRIVER" >&2; exit 1; }
[ -x "$GHIDRA" ] || { echo "missing Ghidra analyzeHeadless: $GHIDRA" >&2; exit 1; }

PYTHONPATH="$ROOT/tools/emu${PYTHONPATH:+:$PYTHONPATH}" \
  python3 "$ROOT/tools/emu/scan_mips16_imports.py" \
  "$DRIVER" \
  --require-selector 15 \
  --require-selector 17

WORK=$(mktemp -d "${TMPDIR:-/private/tmp}/m30-ghidra-import.XXXXXX")
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/project"

set +e
JAVA_HOME_OVERRIDE="$JAVA_HOME_OVERRIDE" \
GHIDRA_JAVA_OPTIONS="${GHIDRA_JAVA_OPTIONS:--Duser.home=$WORK/home}" \
  "$GHIDRA" "$WORK/project" m30imports \
  -import "$DRIVER" \
  -loader BinaryLoader \
  -processor 'MIPS:LE:32:default' \
  -noanalysis \
  -scriptPath "$ROOT/tools/ghidra" \
  -postScript FlatLoad.java "$DRIVER" 0x260db980 0x9674 0x80c \
  -postScript MapSegmentsKeep.java 1 \
    "$DRIVER" 0xbfc08a00 0x1200 0x2fc 1 \
  -postScript MapSegmentsKeep.java 1 \
    "$DRIVER" 0x260db980 0x9e80 0x220 0 \
  -postScript DumpAt.java 0x260e5780,0xbfc09c00 "$WORK/decomp.c" \
  -postScript DumpWords.java 0x260e59e8 0x260e59f0 \
  -postScript FindMips16Imports.java 0x260e4ff4 0x260e5800 15,17 \
  2>&1 | tee "$WORK/ghidra.log"
STATUS=${PIPESTATUS[0]}
set -e
[ "$STATUS" -eq 0 ] || exit "$STATUS"
grep -q 'MIPS16_IMPORT_SUMMARY calls=5' "$WORK/ghidra.log"
grep -q 'MIPS16_IMPORT_TOTAL selector=0xf count=1' "$WORK/ghidra.log"
grep -q 'MIPS16_IMPORT_TOTAL selector=0x11 count=1' "$WORK/ghidra.log"
grep -q 'DumpAt: 260e5780 -> FUN_260e5780' "$WORK/ghidra.log"
grep -q 'DumpAt: bfc09c00 -> FUN_bfc09c00' "$WORK/ghidra.log"
grep -q 'WORD address=260e59e8 value=0xbfc09c05' "$WORK/ghidra.log"
grep -q 'WORD address=260e59ec value=0xbfc09c01' "$WORK/ghidra.log"
grep -q 'trap(0)' "$WORK/decomp.c"
# Mapping the literal pool can change Ghidra's autogenerated variable names
# (pcRam260e59e8 vs _UNK_260e59e8). Assert the address and argument shape,
# not a presentation-specific symbol spelling.
grep -Eq '\(\*[^;]*260e59e8\)\(\*param_4,0,param_1,0xf\);' "$WORK/decomp.c"
grep -Eq '\(\*[^;]*\)\(\*param_4,auStack_90,0x1c,0x11\);' "$WORK/decomp.c"

echo 'DRV_UI IMPORT PASS selectors=15,17'
