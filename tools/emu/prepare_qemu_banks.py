#!/usr/bin/env python3
"""Prepare real Actions .ap banks for a future QEMU user-mode harness.

The M30 overlay loader places each AP bank at the virtual address recorded in
the AP table.  This tool preserves that layout in an assembly include and a
linker script, so a harness cannot accidentally concatenate banks or relocate
the Ghidra addresses it is meant to exercise.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
from dataclasses import asdict, dataclass
from pathlib import Path


@dataclass(frozen=True)
class Bank:
    index: int
    file_offset: int
    virtual_address: int
    size: int
    payload: str


def parse_banks(ap: Path) -> tuple[bytes, list[Bank]]:
    data = ap.read_bytes()
    if data[4:8] != b"yqhx":
        raise ValueError(f"not an Actions AP file: {ap}")
    table_words = struct.unpack_from("<I", data, 0x2C)[0]
    banks: list[Bank] = []
    for offset in range(0x100, 0x100 + table_words - 11, 12):
        file_offset, virtual_address, size = struct.unpack_from("<III", data, offset)
        if not (file_offset and virtual_address and size):
            continue
        if file_offset + size > len(data):
            raise ValueError(f"bank at table offset 0x{offset:x} exceeds AP size")
        banks.append(Bank(len(banks), file_offset, virtual_address, size, ""))
    if not banks:
        raise ValueError(f"no loadable banks in {ap}")
    by_address = sorted(banks, key=lambda bank: bank.virtual_address)
    for left, right in zip(by_address, by_address[1:]):
        if left.virtual_address + left.size > right.virtual_address:
            raise ValueError(f"overlapping banks at 0x{left.virtual_address:x} and 0x{right.virtual_address:x}")
    return data, banks


def prepare(ap: Path, out: Path, *, max_virtual_address: int | None = None) -> dict[str, object]:
    data, original_banks = parse_banks(ap)
    if max_virtual_address is not None:
        original_banks = [
            bank for bank in original_banks
            if bank.virtual_address <= max_virtual_address
        ]
    out.mkdir(parents=True, exist_ok=True)
    payload_dir = out / "banks"
    payload_dir.mkdir(exist_ok=True)
    banks: list[Bank] = []
    for bank in original_banks:
        payload = payload_dir / f"{bank.index:03d}_{bank.virtual_address:08x}.bin"
        payload.write_bytes(data[bank.file_offset:bank.file_offset + bank.size])
        banks.append(Bank(bank.index, bank.file_offset, bank.virtual_address, bank.size, str(payload)))

    asm_lines = [
        "/* generated by tools/emu/prepare_qemu_banks.py; do not edit */",
        ".set noreorder",
    ]
    ld_lines = [
        "/* generated linker fragment; include this from the QEMU harness linker script */",
    ]
    for bank in banks:
        section = f".bank_{bank.virtual_address:08x}"
        symbol = f"bank_{bank.virtual_address:08x}"
        asm_lines += [
            f'.section {section},"ax",@progbits',
            f".globl {symbol}",
            f"{symbol}:",
            f'.incbin "banks/{bank.index:03d}_{bank.virtual_address:08x}.bin"',
        ]
        ld_lines += [
            f". = 0x{bank.virtual_address:08x};",
            f"{section} : {{ KEEP(*({section})) }}",
        ]
    (out / "banks.s").write_text("\n".join(asm_lines) + "\n")
    (out / "banks.ld").write_text("\n".join(ld_lines) + "\n")
    manifest = {
        "source": str(ap),
        "source_sha256": hashlib.sha256(data).hexdigest(),
        "max_virtual_address": (
            f"0x{max_virtual_address:08x}" if max_virtual_address is not None else None
        ),
        "bank_count": len(banks),
        "banks": [asdict(bank) for bank in banks],
        "audited_scroll_call": {
            "virtual_address": "0x40d55078",
            "bank": next((bank.virtual_address for bank in banks if bank.virtual_address <= 0x40D55078 < bank.virtual_address + bank.size), None),
        },
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ap", type=Path)
    parser.add_argument("out", type=Path)
    args = parser.parse_args()
    manifest = prepare(args.ap, args.out)
    print(f"prepared {manifest['bank_count']} banks in {args.out}")
    target = manifest["audited_scroll_call"]["bank"]
    if target is None:
        raise SystemExit("audited scroll call is not covered by the AP bank table")
    print(f"scroll call 0x40d55078 is in bank 0x{target:08x}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
